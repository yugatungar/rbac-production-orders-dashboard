CREATE TABLE IF NOT EXISTS PRODUCTION_ORDERS (
    ORDER_ID     VARCHAR NOT NULL,
    ENGINE_MODEL VARCHAR,
    PLANT        VARCHAR,
    STATUS       VARCHAR,
    QTY_PLANNED  NUMBER,
    QTY_BUILT    NUMBER,
    DEFECT_COUNT NUMBER,
    TARGET_DATE  DATE,
    OWNER        VARCHAR,
    REMARKS      VARCHAR,
    UPDATED_AT   TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);