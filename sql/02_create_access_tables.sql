-- Structure only. Safe to run more than once.

CREATE TABLE IF NOT EXISTS APP_ROLES (
    ROLE_NAME   VARCHAR NOT NULL,
    DESCRIPTION VARCHAR,
    ROW_SCOPE   VARCHAR NOT NULL DEFAULT 'ALL'
);

CREATE TABLE IF NOT EXISTS ROLE_PAGE_ACCESS (
    ROLE_NAME VARCHAR NOT NULL,
    PAGE_NAME VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS ROLE_COLUMN_ACCESS (
    ROLE_NAME   VARCHAR NOT NULL,
    COLUMN_NAME VARCHAR NOT NULL,
    CAN_VIEW    BOOLEAN NOT NULL DEFAULT FALSE,
    CAN_EDIT    BOOLEAN NOT NULL DEFAULT FALSE,
    TABLE_NAME  VARCHAR
);

ALTER TABLE ROLE_COLUMN_ACCESS ADD COLUMN IF NOT EXISTS TABLE_NAME VARCHAR;

CREATE TABLE IF NOT EXISTS APP_USERS (
    USERNAME        VARCHAR NOT NULL,
    DISPLAY_NAME    VARCHAR,
    PASSWORD_HASH   VARCHAR NOT NULL,
    ROLE_NAME       VARCHAR NOT NULL,
    IS_ACTIVE       BOOLEAN NOT NULL DEFAULT TRUE,
    FAILED_ATTEMPTS NUMBER  NOT NULL DEFAULT 0,
    LOCKED_UNTIL    TIMESTAMP_LTZ,
    LAST_LOGIN      TIMESTAMP_LTZ,
    CREATED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS AUDIT_LOG (
    EVENT_TIME TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    USERNAME   VARCHAR,
    ACTION     VARCHAR,
    DETAIL     VARCHAR
);

CREATE TABLE IF NOT EXISTS DATASETS (
    TABLE_NAME   VARCHAR NOT NULL,
    DISPLAY_NAME VARCHAR,
    OWNER_COLUMN VARCHAR
);

CREATE TABLE IF NOT EXISTS ROLE_DATASET_ACCESS (
    ROLE_NAME  VARCHAR NOT NULL,
    TABLE_NAME VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS METRICS (
    METRIC_ID   VARCHAR NOT NULL,
    TABLE_NAME  VARCHAR NOT NULL,
    LABEL       VARCHAR NOT NULL,
    KIND        VARCHAR NOT NULL,
    COL_A       VARCHAR NOT NULL,
    COL_B       VARCHAR NOT NULL,
    VALUE_FORMAT VARCHAR
);

CREATE TABLE IF NOT EXISTS COLUMN_DESCRIPTIONS (
    TABLE_NAME  VARCHAR NOT NULL,
    COLUMN_NAME VARCHAR NOT NULL,
    DESCRIPTION VARCHAR,
    STATUS      VARCHAR DEFAULT 'APPROVED'
);

CREATE TABLE IF NOT EXISTS ADMIN_CHANGE_LOG (
    CHANGED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    ADMIN_USER VARCHAR,
    ACTION     VARCHAR,
    TABLE_NAME VARCHAR,
    DETAILS    VARCHAR
);

CREATE TABLE IF NOT EXISTS AGENT_LOG (
    EVENT_TIME    TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    USERNAME      VARCHAR,
    QUESTION      VARCHAR,
    OUTCOME       VARCHAR,
    ATTEMPTS      NUMBER,
    REQUEST       VARCHAR,
    ROWS_RETURNED NUMBER
);