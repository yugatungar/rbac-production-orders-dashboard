INSERT INTO DATASETS (TABLE_NAME, DISPLAY_NAME, OWNER_COLUMN)
SELECT 'PRODUCTION_ORDERS', 'Production orders', 'OWNER'
WHERE NOT EXISTS (
    SELECT 1 FROM DATASETS WHERE TABLE_NAME = 'PRODUCTION_ORDERS'
);

DELETE FROM ROLE_DATASET_ACCESS WHERE TABLE_NAME = 'PRODUCTION_ORDERS';
INSERT INTO ROLE_DATASET_ACCESS (ROLE_NAME, TABLE_NAME)
SELECT r.ROLE_NAME, 'PRODUCTION_ORDERS'
FROM (VALUES ('ADMIN'), ('ANALYST'), ('OPERATOR'), ('DEVELOPER'), ('LEADERSHIP')) AS r(ROLE_NAME);

DELETE FROM ROLE_COLUMN_ACCESS WHERE TABLE_NAME = 'PRODUCTION_ORDERS';
INSERT INTO ROLE_COLUMN_ACCESS (ROLE_NAME, COLUMN_NAME, CAN_VIEW, CAN_EDIT, TABLE_NAME)
SELECT
    r.ROLE_NAME,
    c.COLUMN_NAME,
    CASE r.ROLE_NAME
        WHEN 'ADMIN'      THEN TRUE
        WHEN 'DEVELOPER'  THEN TRUE
        WHEN 'OPERATOR'   THEN TRUE
        WHEN 'ANALYST'    THEN c.COLUMN_NAME <> 'REMARKS'
        WHEN 'LEADERSHIP' THEN c.COLUMN_NAME NOT IN ('OWNER', 'REMARKS', 'UPDATED_AT')
    END,
    CASE r.ROLE_NAME
        WHEN 'ADMIN'    THEN c.COLUMN_NAME IN ('STATUS', 'QTY_PLANNED', 'QTY_BUILT', 'DEFECT_COUNT', 'TARGET_DATE', 'REMARKS')
        WHEN 'OPERATOR' THEN c.COLUMN_NAME IN ('STATUS', 'QTY_BUILT', 'DEFECT_COUNT', 'REMARKS')
        ELSE FALSE
    END,
    'PRODUCTION_ORDERS'
FROM (VALUES ('ADMIN'), ('ANALYST'), ('OPERATOR'), ('DEVELOPER'), ('LEADERSHIP')) AS r(ROLE_NAME)
CROSS JOIN (VALUES
    ('ORDER_ID'), ('ENGINE_MODEL'), ('PLANT'), ('STATUS'), ('QTY_PLANNED'), ('QTY_BUILT'),
    ('DEFECT_COUNT'), ('TARGET_DATE'), ('OWNER'), ('REMARKS'), ('UPDATED_AT')
) AS c(COLUMN_NAME)
