TRUNCATE TABLE PRODUCTION_ORDERS;

INSERT INTO PRODUCTION_ORDERS
    (ORDER_ID, ENGINE_MODEL, PLANT, STATUS, QTY_PLANNED, QTY_BUILT, DEFECT_COUNT, TARGET_DATE, OWNER)
SELECT
    'ORD-' || LPAD(SEQ4()::VARCHAR, 5, '0'),
    DECODE(UNIFORM(1, 4, RANDOM()), 1, 'B6.7', 2, 'L9', 3, 'X15', 4, 'QSB'),
    DECODE(UNIFORM(1, 3, RANDOM()), 1, 'Pune', 2, 'Jamshedpur', 3, 'Phaltan'),
    DECODE(UNIFORM(1, 4, RANDOM()), 1, 'PLANNED', 2, 'IN_PROGRESS', 3, 'ON_HOLD', 4, 'COMPLETED'),
    UNIFORM(50, 500, RANDOM()),
    UNIFORM(0, 400, RANDOM()),
    UNIFORM(0, 12, RANDOM()),
    DATEADD(day, UNIFORM(-120, 90, RANDOM()), CURRENT_DATE()),
    DECODE(UNIFORM(1, 4, RANDOM()), 1, 'operator1', 2, 'operator1', 3, 'admin', 4, 'developer1')
FROM TABLE(GENERATOR(ROWCOUNT => 300));

UPDATE PRODUCTION_ORDERS SET QTY_BUILT = LEAST(QTY_BUILT, QTY_PLANNED);

UPDATE PRODUCTION_ORDERS SET QTY_BUILT = QTY_PLANNED WHERE STATUS = 'COMPLETED';

UPDATE PRODUCTION_ORDERS SET QTY_BUILT = 0 WHERE STATUS = 'PLANNED';
